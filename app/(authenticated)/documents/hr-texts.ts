export interface PdpaSection {
  title: string
  /** ย่อหน้าเดียว */
  body?: string
  /** รายการแบบเลข 1. 2. 3. */
  items?: string[]
}

export interface PdpaText {
  intro: string
  sections: PdpaSection[]
}

/** สีประจำแบบฟอร์ม (ตามกระดาษ) */
export const HR_THEME: Record<'JA' | 'IA' | 'RS', string> = {
  JA: '#1f4e5f',
  IA: '#9b1c1c',
  RS: '#9b1c1c',
}

const SHARED_RIGHTS =
  'ท่านมีสิทธิขอเข้าถึง ขอรับสำเนา ขอแก้ไข ขอลบ ขอระงับการใช้ หรือคัดค้านการประมวลผลข้อมูลส่วนบุคคลของท่าน รวมถึงสิทธิในการถอนความยินยอมเมื่อใดก็ได้ โดยการถอนความยินยอมจะไม่ส่งผลกระทบต่อการเก็บรวบรวม ใช้ หรือเปิดเผยข้อมูล ที่ได้ดำเนินการไปแล้วก่อนการถอนความยินยอม'

/**
 * "บริษัท X จำกัด" — ข้อความบนกระดาษขึ้นต้นด้วย "บริษัท" เสมอ
 * ponytail: brand.name_th บางแบรนด์มีคำว่า "บริษัท" อยู่แล้ว เติมซ้ำจะได้ "บริษัท บริษัท ..."
 */
export const companyName = (nameTh: string) =>
  nameTh.trim().startsWith('บริษัท') ? nameTh.trim() : `บริษัท ${nameTh.trim()}`

/** เนื้อหานโยบาย PDPA ของใบสมัครงาน (JA) / ใบสมัครฝึกงาน (IA) */
export function pdpaText(kind: 'JA' | 'IA', nameTh: string, address: string): PdpaText {
  const co = companyName(nameTh)
  const subject = kind === 'JA' ? 'ผู้สมัครงาน' : 'นักศึกษาฝึกงาน'
  const intro =
    `${co} ("บริษัท") ตระหนักถึงความสำคัญของการคุ้มครองข้อมูลส่วนบุคคลของท่าน และเคารพสิทธิความเป็นส่วนตัวของ${subject}ตามพระราชบัญญัติคุ้มครองข้อมูลส่วนบุคคล พ.ศ. 2562 (Personal Data Protection Act: PDPA) จึงขอแจ้งรายละเอียดการเก็บรวบรวม ใช้ และเปิดเผยข้อมูลส่วนบุคคลของท่าน ดังนี้`

  const contact: PdpaSection = {
    title: '6) ช่องทางการติดต่อ',
    body: `ฝ่ายบุคคล ${co} ${address}`,
  }

  if (kind === 'JA') {
    return {
      intro,
      sections: [
        {
          title: '1) ข้อมูลที่เก็บรวบรวม',
          body: 'ข้อมูลตามที่ระบุในใบสมัครงานฉบับนี้ เช่น ชื่อ-นามสกุล วัน เดือน ปีเกิด เลขบัตรประจำตัวประชาชน ที่อยู่ ข้อมูลติดต่อ ประวัติการศึกษา ประวัติการทำงาน รูปถ่าย และเอกสารประกอบการสมัครอื่นใดที่ท่านส่งมอบให้แก่บริษัท',
        },
        {
          title: '2) วัตถุประสงค์ในการเก็บรวบรวม ใช้ และเปิดเผยข้อมูล',
          items: [
            'เพื่อใช้ในกระบวนการพิจารณาคัดเลือกและสรรหาบุคลากรเข้าทำงานกับบริษัท',
            'เพื่อติดต่อสื่อสารกับผู้สมัครเกี่ยวกับสถานะการสมัครและการนัดหมายสัมภาษณ์',
            'เพื่อตรวจสอบคุณสมบัติและประวัติที่เกี่ยวข้องกับการสมัครงาน (หากจำเป็น)',
            'เพื่อจัดทำสัญญาจ้างงาน กรณีที่ท่านผ่านการคัดเลือก',
            'เพื่อปฏิบัติตามกฎหมายหรือกฎระเบียบที่เกี่ยวข้อง',
          ],
        },
        {
          title: '3) การเก็บรักษาและระยะเวลาการเก็บข้อมูล',
          body: 'บริษัทจะเก็บรักษาข้อมูลส่วนบุคคลของท่านไว้เป็นระยะเวลาไม่เกิน 1 ปี นับแต่วันที่ได้รับใบสมัคร เพื่อวัตถุประสงค์ในการพิจารณาตำแหน่งงานที่ท่านอาจสนใจในอนาคต หลังจากนั้นบริษัทจะทำการลบหรือทำลายข้อมูลของท่านอย่างปลอดภัย เว้นแต่ท่านผ่านการคัดเลือกและได้เข้าเป็นพนักงาน ซึ่งข้อมูลจะถูกเก็บต่อไปตามระยะเวลาการเป็นพนักงานและตามที่กฎหมายกำหนด',
        },
        {
          title: '4) การเปิดเผยข้อมูล',
          body: 'บริษัทจะไม่เปิดเผยข้อมูลส่วนบุคคลของท่านแก่บุคคลภายนอก เว้นแต่ในกรณีที่จำเป็นต่อกระบวนการสรรหาบุคลากร (เช่น หน่วยงานตรวจสอบประวัติที่บริษัทว่าจ้าง) หรือตามที่กฎหมายกำหนดหรือได้รับความยินยอมจากท่าน',
        },
        { title: '5) สิทธิของเจ้าของข้อมูลส่วนบุคคล', body: SHARED_RIGHTS },
        contact,
      ],
    }
  }

  return {
    intro,
    sections: [
      {
        title: '1) ข้อมูลที่เก็บรวบรวม',
        body: 'ข้อมูลตามที่ระบุในใบสมัครฝึกงานฉบับนี้ เช่น ชื่อ-นามสกุล วัน เดือน ปีเกิด เลขบัตรประจำตัวประชาชน ที่อยู่ ข้อมูลติดต่อ ข้อมูลการศึกษา รูปถ่าย และเอกสารประกอบการสมัครอื่นใดที่ท่านส่งมอบให้แก่บริษัท',
      },
      {
        title: '2) วัตถุประสงค์ในการเก็บรวบรวม ใช้ และเปิดเผยข้อมูล',
        items: [
          'เพื่อใช้ในกระบวนการพิจารณาคัดเลือกนักศึกษาเข้ารับการฝึกงานกับบริษัท',
          'เพื่อติดต่อสื่อสารกับผู้สมัครและสถานศึกษาเกี่ยวกับการฝึกงาน',
          'เพื่อจัดทำเอกสารตอบรับ/หนังสือรับรองการฝึกงาน และแบบประเมินผลการฝึกงาน',
          'เพื่อการดูแลความปลอดภัยและสวัสดิภาพของนักศึกษาระหว่างการฝึกงาน',
          'เพื่อปฏิบัติตามกฎหมายหรือข้อกำหนดของสถานศึกษาที่เกี่ยวข้อง',
        ],
      },
      {
        title: '3) การเก็บรักษาและระยะเวลาการเก็บข้อมูล',
        body: 'บริษัทจะเก็บรักษาข้อมูลส่วนบุคคลของท่านไว้ตลอดระยะเวลาการฝึกงานและต่อเนื่องอีกไม่เกิน 1 ปี นับแต่วันสิ้นสุดการฝึกงาน เพื่อวัตถุประสงค์ในการออกเอกสารรับรองหรือใช้อ้างอิงในอนาคต หลังจากนั้นบริษัทจะทำการลบหรือทำลายข้อมูลของท่านอย่างปลอดภัย',
      },
      {
        title: '4) การเปิดเผยข้อมูล',
        body: 'บริษัทอาจเปิดเผยข้อมูลบางส่วนแก่สถานศึกษาต้นสังกัดของท่าน เพื่อวัตถุประสงค์ในการประเมินผลและรับรองการฝึกงาน และจะไม่เปิดเผยข้อมูลแก่บุคคลภายนอกอื่นใด เว้นแต่ตามที่กฎหมายกำหนดหรือได้รับความยินยอมจากท่าน',
      },
      { title: '5) สิทธิของเจ้าของข้อมูลส่วนบุคคล', body: SHARED_RIGHTS },
      contact,
    ],
  }
}

